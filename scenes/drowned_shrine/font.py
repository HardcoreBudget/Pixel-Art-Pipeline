def mask(text, font, spacing=1):
    glyphs = [font[ch] for ch in text.upper()]
    h = len(glyphs[0])
    w = sum(len(g[0]) for g in glyphs) + spacing * (len(glyphs) - 1)
    m = np.zeros((h, w), bool)
    x = 0
    for g in glyphs:
        for y, row in enumerate(g):
            for dx, ch in enumerate(row):
                if ch == "#":
                    m[y, x + dx] = True
        x += len(g[0]) + spacing
    return m


def text(s, font=SMALL, fill="cream2", shade=None, outline="ink", shadow=False, spacing=1):
    """Render s as RGBA. fill is one colour or a list of colours top to bottom (a gradient by row); shade colours
    the glyph's lower rows (a 1-colour bevel); outline draws an 8-way 1-px outline; shadow drops it 1 px down."""
    m = mask(s, font, spacing)
    h, w = m.shape
    img = canvas(w + 2, h + 3)
    mm = np.zeros(img.shape[:2], bool)
    mm[1:1 + h, 1:1 + w] = m
    if outline:
        ring = ndimage.binary_dilation(mm, np.ones((3, 3), bool)) & ~mm
        if shadow:
            ring |= np.roll(ring, 1, 0) & ~mm
        img[ring] = C[outline]
    fills = fill if isinstance(fill, list) else [fill]
    for y in range(h):
        col = fills[min(len(fills) - 1, y * len(fills) // h)]
        row = mm[1 + y]
        img[1 + y][row] = C[col]
    if shade:
        low = mm & ~np.roll(mm, -1, 0)          # the bottom pixel of each stroke
        img[low] = C[shade]
    return img


